/**
 * 시나리오별 system prompt 합성기.
 * 발음 규칙을 항상 맨 앞에 두고, 역할/대화흐름은 뒤에 이어붙입니다.
 */
export function buildKoreanInstructions(opts: {
  role: string;
  flow: string;
  personaName?: string;
  personaContext?: string;
}): string {
  const { role, flow, personaName, personaContext } = opts;
  const persona = personaName?.trim() || "어르신";
  const ctx = personaContext?.trim();
  return [
    KOREAN_ANNOUNCER_RULES,
    "",
    `[역할]\n${role.replace(/\$\{personaName\}/g, persona)}`,
    ctx ? `\n[참고 정보]\n${ctx}` : "",
    "",
    `[대화 흐름]\n${flow}`,
  ]
    .filter(Boolean)
    .join("\n");
}

